/**
 * 数据源契约 —— 「怎么把 `data/` 里的 JSON 取到内存」这一件事的接口。
 *
 * ## 为什么需要这层抽象
 *
 * 同一个游戏跑在两个宿主里，而这两个宿主**读文件的方式根本不同**：
 *
 *   | 宿主 | 取数方式 | 时机 |
 *   | --- | --- | --- |
 *   | 网页端 | `import.meta.glob` / 静态 `import` —— Vite 把 JSON 烘进 bundle | 构建期 |
 *   | 微信小游戏 | `wx.getFileSystemManager().readFileSync('data/…', 'utf8')` | 运行期 |
 *
 * 网页端这么做是对的（静态站点，一次加载、零请求数）；但小游戏端有两个理由必须改：
 *
 *   1. **便于查看**：小游戏包里躺着一份 `data/*.json`，想确认「第 37 层到底怎么摆的」
 *      直接打开那个文件就行，不必在 2MB 的 `game.js` 里翻字面量。
 *   2. **主包体积弹性**：数据从 bundle 里出来之后，
 *      将来改成分包 / 按需加载才是可能的（现在 51 层是硬塞进主包的）。
 *
 * ## 接口只有一个方法，是刻意的
 *
 * 不给 `listDir()` / `exists()` 这类能力 —— 一旦开了口子，
 * 两端就会各自长出对方没有的行为，最后「同一份数据读出两个结果」找不出来。
 * 只有 `read(key)` 时，能出问题的地方只剩「这个 key 在不在」，
 * 而那是 `index.ts` 的穷尽断言负责的。
 */

export interface JsonSource {
  /**
   * 自述一行 —— 用来写进启动诊断。
   *
   * 有它才能在「IDE 里数据不对」这类问题上**先回答「是哪一端在读」**：
   * 网页端与我这台机器上的小游戏包，是两条完全不同的取数路径。
   */
  readonly label: string;

  /**
   * 读一个 JSON 文件并解析。
   *
   * `key` 一律**相对仓库根的 `data/` 目录**，形如 `tiles.json` /
   * `floors/floor-01.json`；**不带前导 `./` 或 `/`**。
   *
   * ⚠️ 这个约定不是随便定的：小游戏侧直接把 `data/${key}` 交给
   * `readFileSync`，而微信官方文档「文件系统 → 访问代码包文件」明确写了
   * 「从项目根目录开始写文件路径，不支持相对路径的写法，`./a/b/c` `../a/b/c` 不合法」。
   * 所以带前缀的 key 会在真机上直接读不到 —— 让 key 的格式在这里就归一，
   * 胜过在两端各写一次字符串拼接。
   *
   * 读不到时**必须抛**，不要返回 `undefined`：
   * 一个缺文件的楼层会让游戏「看起来能跑、那一层是空的」，比当场炸难查得多。
   */
  read<T>(key: string): T;
}
